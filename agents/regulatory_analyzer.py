"""Regulatory & Permitting Automation Agent (RegTech).

Ported from global-compliance-ai (app/agents/regulatory.py). Unlike the contract-risk pipeline,
this module maps a project spec to required permits/licenses and drafts/audits the submission —
the three agents CLAUDE.md's Module 2 describes:
  1. Requirement_Extractor_Agent -> requirement_extractor()
  2. Dossier_Drafter_Agent       -> dossier_drafter()
  3. Compliance_Gap_Analyzer     -> gap_analyzer()

Output is framed as an analytics/gap report, not a legal opinion, matching the same LegalOps
Analytics positioning as the contract pipeline; every gap/requirement traces to a legal_basis.
"""
from agents.regulatory_ontology import RegulatoryGraph

DISCLAIMER = {
    "ko": "본 리포트는 인허가 요건 분석 및 신청서 초안 지원 도구(RegOps Analytics)의 산출물이며 "
          "법률 자문이 아닙니다. 제출 전 반드시 담당자/전문가가 검토해야 합니다.",
    "en": "This report is generated by a permitting requirement analysis and dossier-drafting "
          "support tool (RegOps Analytics), not legal advice. A qualified reviewer must check it "
          "before submission.",
}


def requirement_extractor(country: str, sector: str, graph: RegulatoryGraph) -> list[dict]:
    """Map a project's (country, sector) to the permits/licenses it needs, in dependency order."""
    return graph.requirements(country, sector)


def dossier_drafter(project_name: str, requirements: list[dict]) -> dict[str, str]:
    """Produce a skeleton application draft per permit. A stub today; swap in an LLM call that
    fills each authority's template the same way contract_generator.py fills contract templates."""
    drafts = {}
    for r in requirements:
        drafts[r["permit"]] = (
            f"[초안] {r['authority']} 제출용 '{r['permit']}' 신청서 - 사업명: {project_name}, "
            f"제출서류: {', '.join(r['documents'])}. 세부 항목은 담당자가 작성/검토해야 합니다."
        )
    return drafts


def gap_analyzer(requirements: list[dict], submitted: dict[str, str]) -> list[dict]:
    """submitted maps document name -> content; missing or under-20-char entries are flagged."""
    gaps = []
    for r in requirements:
        for doc in r["documents"]:
            if doc not in submitted:
                gaps.append({"permit": r["permit"], "document": doc, "status": "missing", "detail": ""})
            elif len(submitted[doc].strip()) < 20:
                gaps.append({"permit": r["permit"], "document": doc, "status": "insufficient",
                            "detail": "내용이 지나치게 짧습니다."})
    return gaps


def run_regulatory_pipeline(project_name: str, country: str, sector: str, submitted: dict[str, str],
                            graph: RegulatoryGraph, language: str = "ko") -> dict:
    requirements = requirement_extractor(country, sector, graph)
    return {
        "requirements": requirements,
        "gaps": gap_analyzer(requirements, submitted),
        "drafts": dossier_drafter(project_name, requirements),
        "disclaimer": DISCLAIMER.get(language, DISCLAIMER["ko"]),
    }
